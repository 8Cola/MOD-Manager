param([Parameter(Mandatory=$true)][ValidateSet('test','release','dev','check','fmt','build')][string]$Task)
$ErrorActionPreference='Stop'
$projectRoot=Split-Path $PSScriptRoot -Parent
$localTools=Join-Path $projectRoot '_local/tools'
if (-not (Test-Path -LiteralPath $localTools)) { $localTools=Join-Path $projectRoot '.tools' }
if (Test-Path -LiteralPath (Join-Path $projectRoot '_local')) {
  $env:CARGO_TARGET_DIR=Join-Path $projectRoot '_local/target'
}
if (Test-Path (Join-Path $localTools 'cargo/bin/cargo.exe')) {
  $env:CARGO_HOME=Join-Path $localTools 'cargo'
  $env:RUSTUP_HOME=Join-Path $localTools 'rustup'
  $env:RUSTUP_TOOLCHAIN='stable'
  if (Test-Path (Join-Path $localTools 'registry-cache')) { $env:CARGO_NET_OFFLINE='true' }
  $env:PATH="$(Join-Path $localTools 'cargo/bin');$env:PATH"
}
$setup=Join-Path $localTools 'msvc/setup_x64.bat'
if (Test-Path $setup) {
  # Read environment generated by the portable toolchain; never delete/move files across shells.
  & cmd.exe /d /c "call `"$setup`" >nul && set" | ForEach-Object {
    if ($_ -match '^([^=]+)=(.*)$') { [Environment]::SetEnvironmentVariable($Matches[1],$Matches[2],'Process') }
  }
}
Push-Location $projectRoot
try {
  switch ($Task) {
    'test' { cargo test --manifest-path src-tauri/Cargo.toml --lib }
    'check' { cargo check --manifest-path src-tauri/Cargo.toml }
    'build' { cargo build --manifest-path src-tauri/Cargo.toml }
    'fmt' { cargo fmt --manifest-path src-tauri/Cargo.toml }
    'release' { npm.cmd run release }
    'dev' { npm.cmd run desktop }
  }
  if ($LASTEXITCODE -ne 0) { throw "Task $Task failed ($LASTEXITCODE)" }
} finally { Pop-Location }
